package seed

import (
	"fmt"
	"io"
	"maps"
	"slices"
	"strconv"
)

// PathParameters are the OpenAPI path parameters of the demo (BE-171):
// parameter name → a demo row that the main company owner (CompanyEmail)
// or an anonymous caller can read, so a contract fuzzer reaches real 200
// responses instead of 404s on random IDs. The org is CompanyOrgID: the
// public profile anonymously, and every /orgs/{org_id}/... read of its
// owner. A parameter is left out when the demo has no row the company
// owner may read (another org's payee, a user's CV, …).
func (d Demo) PathParameters() map[string]string {
	p := map[string]string{
		"org_id":            d.CompanyOrgID.String(),
		"slug":              d.CompanySlug,
		"club_id":           d.MainClubOrgID.String(),
		"university_id":     d.MainUniversity.ID.String(),
		"event_id":          d.PublicEventID.String(),
		"post_id":           d.PublicPostID.String(),
		"notice_version_id": d.NoticeVersionID.String(),
		"segment_id":        d.SegmentID.String(),
		"entitlement_id":    d.EntitlementID.String(),
		"party_id":          d.Commerce.BuyerPartyID.String(),
		"offering_id":       d.Commerce.PackageOfferingID.String(),
		"order_id":          d.Commerce.PackageOrderID.String(),
	}
	if len(d.MainUniversity.Departments) > 0 {
		p["department_id"] = d.MainUniversity.Departments[0].ID.String()
	}
	return p
}

// WriteSchemathesisConfig writes the demo's PathParameters as a
// Schemathesis (v4) schemathesis.toml: a project-wide [parameters] table
// with location-qualified keys ("path.org_id"), so a query or body field
// of the same name keeps being generated. Schemathesis then uses these
// values for the path parameters of every operation in every phase.
func WriteSchemathesisConfig(w io.Writer, d Demo) error {
	p := d.PathParameters()
	if _, err := io.WriteString(w, "# Generated by `koro seed demo-params` (BE-171) from the demo seed; do not edit.\n[parameters]\n"); err != nil {
		return err
	}
	for _, name := range slices.Sorted(maps.Keys(p)) {
		// strconv.Quote of an ASCII UUID or slug is a valid TOML basic string.
		if _, err := fmt.Fprintf(w, "%s = %s\n", strconv.Quote("path."+name), strconv.Quote(p[name])); err != nil {
			return err
		}
	}
	return nil
}
