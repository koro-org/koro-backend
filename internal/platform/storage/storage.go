// Package storage wraps S3-compatible object storage (05 §14.7, 01 §1.1;
// BE-008). Files never flow through the API: browsers upload with a
// presigned PUT URL and download with a short-lived presigned GET URL, while
// the server reads objects only to verify and scan them.
//
// Two implementations satisfy Objects:
//
//   - S3 (NewS3): aws-sdk-go-v2 with RequestChecksumCalculation and
//     ResponseChecksumValidation set to WhenRequired (R-002 §3i): the SDK's
//     default CRC32 trailer breaks S3-compatible servers (SeaweedFS, local
//     providers). Path-style addressing, static credentials, no environment
//     or shared-file lookups (configuration comes from internal/platform/config).
//   - Mem (NewMem): an in-memory store for service, wiring and matrix tests.
//
// Rules the package enforces for every caller:
//
//   - A presigned GET lives at most MaxGetTTL (5 minutes) and always carries
//     a response Content-Disposition chosen by the caller (files sets
//     "attachment"). A presigned PUT lives at most MaxPutTTL and signs the
//     content type and the exact content length.
//   - Buckets are private: nothing here creates public ACLs or bucket
//     policies, and object keys are generated by the server.
//   - Delete is idempotent: deleting a missing object is not an error.
package storage

import (
	"context"
	"errors"
	"fmt"
	"io"
	"net/http"
	"time"
)

// Presign lifetimes (05 §14.7, 04 §1.14).
const (
	// MaxGetTTL is the longest lifetime of a download URL (≤ 5 minutes).
	MaxGetTTL = 5 * time.Minute
	// MaxPutTTL is the longest lifetime of an upload URL (04 §1.14: 10
	// minutes for createUpload; a slow mobile upload must be able to start).
	MaxPutTTL = 10 * time.Minute
)

// Errors.
var (
	// ErrNotFound: the object (or the bucket) does not exist.
	ErrNotFound = errors.New("storage: object not found")
	// ErrInvalidTTL: a presign lifetime is not positive or exceeds its maximum.
	ErrInvalidTTL = errors.New("storage: invalid presign lifetime")
	// ErrInvalidInput: a required argument is missing.
	ErrInvalidInput = errors.New("storage: invalid input")
)

// Objects is the object storage contract. Every method takes the bucket
// explicitly: the files module keeps uploads in a quarantine bucket until
// they are verified and scanned, then moves them to the main bucket.
type Objects interface {
	// PutObject stores size bytes of body under key (server-generated
	// content such as exports and PDFs).
	PutObject(ctx context.Context, in PutInput) error
	// PresignPut returns a URL the client uploads one object with. The
	// content type and the exact content length are signed: a different
	// size or type is rejected by the server (when it verifies signed
	// headers) and always by files.CompleteUpload.
	PresignPut(ctx context.Context, in PresignPutInput) (Presigned, error)
	// PresignGet returns a download URL valid for ttl (0 < ttl ≤ MaxGetTTL).
	PresignGet(ctx context.Context, in PresignGetInput) (Presigned, error)
	// Stat returns the size and content type of an object, or ErrNotFound.
	Stat(ctx context.Context, bucket, key string) (ObjectInfo, error)
	// Open streams an object, or returns ErrNotFound. The caller closes it.
	Open(ctx context.Context, bucket, key string) (io.ReadCloser, ObjectInfo, error)
	// Copy copies an object server-side and replaces its metadata with
	// in.ContentType and in.ContentDisposition.
	Copy(ctx context.Context, in CopyInput) error
	// Delete removes an object; a missing object is not an error.
	Delete(ctx context.Context, bucket, key string) error
}

// PutInput is the argument of PutObject.
type PutInput struct {
	Bucket, Key        string
	Body               io.Reader
	Size               int64
	ContentType        string
	ContentDisposition string // optional object metadata
}

// PresignPutInput is the argument of PresignPut.
type PresignPutInput struct {
	Bucket, Key   string
	ContentType   string
	ContentLength int64
	TTL           time.Duration // 0 < TTL ≤ MaxPutTTL
}

// PresignGetInput is the argument of PresignGet.
type PresignGetInput struct {
	Bucket, Key string
	TTL         time.Duration // 0 < TTL ≤ MaxGetTTL
	// ResponseContentDisposition and ResponseContentType override the
	// response headers of the download (both required: the browser must
	// never sniff or render an uploaded object inline).
	ResponseContentDisposition string
	ResponseContentType        string
}

// CopyInput is the argument of Copy.
type CopyInput struct {
	SrcBucket, SrcKey  string
	DstBucket, DstKey  string
	ContentType        string
	ContentDisposition string
}

// Presigned is a presigned request.
type Presigned struct {
	URL    string
	Method string
	// Headers are the headers the client must send with the request
	// (signed, except Host and Content-Length which HTTP clients set).
	Headers   map[string]string
	ExpiresAt time.Time
}

// ObjectInfo describes a stored object.
type ObjectInfo struct {
	Size        int64
	ContentType string
}

// checkTTL validates a presign lifetime.
func checkTTL(ttl, maxTTL time.Duration) error {
	if ttl <= 0 || ttl > maxTTL {
		return fmt.Errorf("%w: %s (allowed 0 < ttl ≤ %s)", ErrInvalidTTL, ttl, maxTTL)
	}
	return nil
}

func (in PresignPutInput) validate() error {
	if in.Bucket == "" || in.Key == "" || in.ContentType == "" || in.ContentLength <= 0 {
		return fmt.Errorf("%w: presign put needs bucket, key, content type and a positive length", ErrInvalidInput)
	}
	return checkTTL(in.TTL, MaxPutTTL)
}

func (in PresignGetInput) validate() error {
	if in.Bucket == "" || in.Key == "" || in.ResponseContentDisposition == "" || in.ResponseContentType == "" {
		return fmt.Errorf("%w: presign get needs bucket, key, response content disposition and type", ErrInvalidInput)
	}
	return checkTTL(in.TTL, MaxGetTTL)
}

func (in PutInput) validate() error {
	if in.Bucket == "" || in.Key == "" || in.Body == nil || in.Size <= 0 || in.ContentType == "" {
		return fmt.Errorf("%w: put needs bucket, key, body, a positive size and a content type", ErrInvalidInput)
	}
	return nil
}

func (in CopyInput) validate() error {
	if in.SrcBucket == "" || in.SrcKey == "" || in.DstBucket == "" || in.DstKey == "" || in.ContentType == "" {
		return fmt.Errorf("%w: copy needs source, destination and a content type", ErrInvalidInput)
	}
	return nil
}

// clientHeaders returns the signed headers a client must send, without the
// ones HTTP clients set themselves (Host, Content-Length; browsers forbid
// setting them).
func clientHeaders(h http.Header) map[string]string {
	out := map[string]string{}
	for k, v := range h {
		switch http.CanonicalHeaderKey(k) {
		case "Host", "Content-Length":
			continue
		}
		if len(v) > 0 {
			out[http.CanonicalHeaderKey(k)] = v[0]
		}
	}
	return out
}
